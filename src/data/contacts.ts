/** Google's favicon service, as used by the app. */
/**
 * Domain → the company's mark, as drawn in the Domain column: one or two white
 * letters on the company's own colour. Grounds resolve against the
 * `--color-brand-*` tokens, which come from the Figma `brand/*` collection.
 */
const BRAND: Record<string, { label: string; className: string }> = {
  'cbre.com': { label: 'CB', className: 'bg-brand-cbre' },
  'paychex.com': { label: 'P', className: 'bg-brand-paychex' },
  'kbr.com': { label: 'KB', className: 'bg-brand-kbr' },
  'boomi.com': { label: 'b', className: 'bg-brand-boomi' },
  'dexterra.com': { label: 'X', className: 'bg-brand-dexterra' },
}

/** Unknown domains fall back to their initial on a neutral ground. */
export function brandMark(domain: string) {
  return BRAND[domain] ?? {
    label: domain.slice(0, 1).toUpperCase(),
    className: 'bg-brand-default',
  }
}

